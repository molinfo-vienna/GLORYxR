from os import PathLike
from pathlib import Path
from typing import Any, Self, override

import joblib
import numpy as np
from fame3r.descriptors import FAME3RVectorizer
from rdkit.Chem.rdChemReactions import ChemicalReaction
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder

from gloryxr.models import ModelProvider
from gloryxr.utils import extract_smiles_for_soms

__all__ = ["MultiFAME3RModelProvider"]


class MultiFAME3RModelProvider(ModelProvider):
    """A model provider for a family of reaction-class specific FAME3R models.

    When used with our provided FAME3R models, predictions generated
    using this class will closely follow those generated by the
    original GLORYx implementation.

    """

    def __init__(self, models: dict[str, Any]) -> None:
        self.models: dict[str, Any] = models
        self.vectorizer = FAME3RVectorizer().fit()

    @classmethod
    def load(cls, model_path: PathLike[str] | str) -> Self:
        """Load a list of reaction-class specific FAME3R models from a local directory.

        The `.joblib` files containing the models should have their
        corresponding reaction type as their file name.

        """

        model_paths = list(Path(model_path).glob("*.joblib"))
        if len(model_paths) == 0:
            raise RuntimeError(f"No models could be found at '{model_path}'")

        models = {}
        for model_path in model_paths:
            models[model_path.stem] = joblib.load(filename=model_path)

        return cls(models)

    @override
    def predict_proba(
        self,
        reactions: list[ChemicalReaction],
    ) -> np.ndarray[tuple[int], np.dtype[np.float64]]:
        results = []

        for rxn in reactions:
            priority = rxn.GetProp("_Priority")
            if priority == "uncommon":
                priority_factor = 0.2
            else:
                priority_factor = 1.0
            subset = rxn.GetProp("_Subset")

            reactive_atoms = extract_smiles_for_soms(rxn.GetReactantTemplate(0))
            if len(reactive_atoms) == 0:
                # TODO: fix this using rules
                results.append(np.nan)
                continue

            descriptors = self.vectorizer.transform(
                np.array(reactive_atoms).reshape(-1, 1)
            )
            predictions = self.models[subset].predict_proba(descriptors)

            results.append(predictions[:, -1].max() * priority_factor)

        return np.asarray(results)


class SingleFAME3RModelProvider(ModelProvider):
    _reaction_classes = [
        "Phase 1 SyGMa rules",
        "CYP rules from GLORY (phase 1)",
        "Other phase 2 rules",
        "UGT rules (phase 2)",
        "GST rules (phase 2)",
        "NAT rules (phase 2)",
        "SULT rules (phase 2)",
        "MT rules (phase 2)",
    ]

    def __init__(self, model: Any) -> None:
        self.model: Any = model
        self.column_transformer = ColumnTransformer(
            [
                (
                    "one_hot_reaction_class",
                    OneHotEncoder(),
                    [0],
                ),
                (
                    "vectorize_atom",
                    FAME3RVectorizer(radius=5, input="smiles"),
                    [1],
                ),
            ]
        ).fit([[x, "[C:1]"] for x in self._reaction_classes])

    @classmethod
    def load(cls, model_path: PathLike[str] | str) -> Self:
        return cls(joblib.load(filename=model_path))

    @override
    def predict_proba(
        self,
        reactions: list[ChemicalReaction],
    ) -> np.ndarray[tuple[int], np.dtype[np.float64]]:
        results = []

        for rxn in reactions:
            priority = rxn.GetProp("_Priority")
            if priority == "uncommon":
                priority_factor = 0.2
            else:
                priority_factor = 1.0
            subset = rxn.GetProp("_Subset")

            reactive_atoms_and_subsets = [
                (subset, smiles)
                for smiles in extract_smiles_for_soms(rxn.GetReactantTemplate(0))
            ]
            if len(reactive_atoms_and_subsets) == 0:
                # TODO: fix this using rules
                results.append(np.nan)
                continue

            descriptors = self.column_transformer.transform(
                np.array(reactive_atoms_and_subsets)
            )
            predictions = self.model.predict_proba(descriptors)

            results.append(predictions[:, -1].max() * priority_factor)

        return np.asarray(results)
